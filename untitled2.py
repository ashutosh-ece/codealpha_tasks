def get_response(message):
    message = message.lower().strip()

    if message in ["hello", "hi", "hey"]:
        return "Hi!"

    elif message in ["how are you", "how are you?"]:
        return "I'm fine, thanks!"

    elif message in ["what is your name", "what is your name?"]:
        return "I'm PyBot, your Python chatbot!"

    elif message in ["help", "what can you do"]:
        return "You can greet me, ask how I am, or say goodbye."

    elif message in ["bye", "goodbye", "exit"]:
        return "Goodbye!"

    else:
        return "Sorry, I don't understand that message."


def main():
    print("=== Welcome to PyBot ===")
    print("Chat with me! Type 'bye' to exit.\n")

    while True:
        user_message = input("You: ")
        response = get_response(user_message)

        print("PyBot:", response)

        if user_message.lower().strip() in [
            "bye", "goodbye", "exit"
        ]:
            break


if __name__ == "__main__":
    main()